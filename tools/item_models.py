# Reads a CMaNGOS / VMaNGOS world database dump (item_template) and prints "label|source item id|display id" for
# requested gear, jewelry and Transmog items. Exact item-name matches win; if AZS uses another English armor-slot word,
# a same-set slot synonym may supply the model. Used with verify_item_models.py by the Item models workflow.
# Usage: python3 item_models.py transmog.txt [more files, or plain lists of names] < world.sql
import re, sys

def rows(sql):
    # every INSERT INTO `item_template` ... VALUES (...),(...);
    for m in re.finditer(r"INSERT INTO `item_template`\s*(\([^)]*\))?\s*VALUES\s*(.*?);\s*$", sql, re.S | re.M):
        cols = [c.strip(" `") for c in m.group(1)[1:-1].split(",")] if m.group(1) else None
        body = m.group(2)
        i, n = 0, len(body)
        while i < n:
            if body[i] != "(":
                i += 1
                continue
            vals, cur, j, q = [], "", i + 1, False
            while j < n:
                ch = body[j]
                if q:
                    if ch == "\\" and j + 1 < n: cur += body[j + 1]; j += 2; continue
                    if ch == "'": q = False
                    else: cur += ch
                elif ch == "'": q = True
                elif ch == ",": vals.append(cur); cur = ""
                elif ch == ")": vals.append(cur); break
                else: cur += ch
                j += 1
            yield cols, [v.strip() for v in vals]
            i = j + 1


wanted = {}
byid = {}                                     # a look whose item has another name: item id -> the look's name
for path in sys.argv[1:]:
    text = open(path, encoding="utf-8-sig").read()
    on = "===" not in text                     # a plain list of names: every line
    for line in text.splitlines():
        line = line.strip()
        if line == "===": on = True; continue
        if not on or not line or line.startswith("#"): continue
        f = [x.strip() for x in line.split("|")]
        name = f[2] if len(f) >= 3 else f[0]
        if len(f) >= 6 and f[5].isdigit(): byid[int(f[5])] = name
        else: wanted[name.lower()] = name

# Armor nouns generated by Azeroth Survivors sometimes differ from their original item's English slot word
# (for example "Bracers" vs "Bindings"). Only try the same set name and a synonymous slot; never fuzzy-match
# a different set or an unrelated item.
SLOT_WORDS = [
    {"Bindings", "Bracers"}, {"Breastplate", "Tunic", "Chestpiece"}, {"Gauntlets", "Gloves"},
    {"Greaves", "Boots", "Sabatons"}, {"Legguards", "Leggings", "Legplates", "Pants"},
    {"Mantle", "Spaulders", "Pauldrons", "Shoulders"}, {"Belt", "Girdle"},
    {"Helm", "Cap", "Circlet", "Cover", "Hood", "Crown", "Headpiece"},
    {"Robes", "Vestments"}
]
slot_by_word = {}
for group in SLOT_WORDS:
    for word in group: slot_by_word[word.lower()] = group
aliases = {}
for target in wanted.values():
    # "Gloves of Faith" has its slot before "of"; ordinary set pieces have it at the end.
    m = re.match(r"^(.*?)\s+of\s+(.*)$", target, re.I)
    if m:
        slot, prefix = m.group(1), None
        group = slot_by_word.get(slot.lower())
        variants = [w for w in group if w.lower() != slot.lower()] if group else []
        for word in variants: aliases[(word + " of " + m.group(2)).lower()] = target
    else:
        m = re.match(r"^(.*?)\s+(\S+)$", target)
        if not m: continue
        prefix, slot = m.groups()
        group = slot_by_word.get(slot.lower())
        variants = [w for w in group if w.lower() != slot.lower()] if group else []
        for word in variants: aliases[(prefix + " " + word).lower()] = target

sql = sys.stdin.read()
table = re.search(r"CREATE TABLE `item_template` \((.*?)\n\)", sql, re.S)
declared = [m.group(1) for m in re.finditer(r"^\s*`(\w+)`", table.group(1), re.M)] if table else None
best = {}
priority = {}
for cols, v in rows(sql):
    cols = cols or declared
    if cols is None:
        sys.exit("item_template: no column list")
    d = {k.lower(): x for k, x in zip(cols, v)}
    entry = int(d.get("entry") or 0)
    name = (d.get("name") or "").strip()
    disp = d.get("displayid") or d.get("display_id") or "0"
    disp = int(disp) if disp.isdigit() else 0
    if entry in byid and disp: best[byid[entry]] = (entry, disp); priority[byid[entry]] = 2; continue
    if not name or not disp: continue
    target = wanted.get(name.lower()) or aliases.get(name.lower())
    if target is None: continue
    rank = 2 if name.lower() == target.lower() else 1
    if target not in best or rank > priority[target] or (rank == priority[target] and entry < best[target][0]):
        best[target] = (entry, disp)
        priority[target] = rank
for name in sorted(best):
    print(name + "|" + str(best[name][0]) + "|" + str(best[name][1]))
